"""Wraps DVC to snapshot a validated dataset and record its hash/lineage in the audit log."""

import hashlib
import logging
import subprocess
from pathlib import Path

import pandas as pd

logger = logging.getLogger(__name__)

# Default output directory for versioned datasets.
_VERSIONED_DIR = Path("data/versioned")


# ---------------------------------------------------------------------------
# Public API
# ---------------------------------------------------------------------------


def snapshot_dataset(
    df: pd.DataFrame,
    name: str,
    *,
    versioned_dir: Path | None = None,
) -> str:
    """Persist *df* as a Parquet file, register it with DVC, and return its SHA-256.

    Workflow:

    1. Write *df* to ``data/versioned/<name>.parquet`` (or *versioned_dir*).
    2. Run ``dvc add <path>`` via :func:`subprocess.run`.
    3. Compute the SHA-256 hex digest of the written file.
    4. Log the hash for downstream audit-log consumption.

    The ``.dvc`` file generated by step 2 should be committed to Git as part
    of the governance trail.

    Args:
        df:           The validated DataFrame to snapshot.
        name:         Logical dataset name, used as the Parquet filename stem
                      (e.g. ``"latest"`` → ``data/versioned/latest.parquet``).
        versioned_dir: Override the default ``data/versioned/`` directory.
                       Useful in tests to avoid touching the real DVC workspace.

    Returns:
        The 64-character lowercase SHA-256 hex digest of the written Parquet
        file, suitable for recording in the audit log.

    Raises:
        ValueError: If *df* is empty.
        subprocess.CalledProcessError: If the ``dvc add`` command fails (exit
            code non-zero), propagated directly so the caller / Prefect flow
            can handle it.
        OSError: If the file cannot be written to *versioned_dir*.
    """
    if df.empty:
        raise ValueError(
            f"snapshot_dataset received an empty DataFrame for name={name!r} — "
            "refusing to version an empty snapshot."
        )

    target_dir = (versioned_dir or _VERSIONED_DIR).resolve()
    target_dir.mkdir(parents=True, exist_ok=True)

    dest = target_dir / f"{name}.parquet"
    logger.info("Writing versioned snapshot to %s (%d rows) …", dest, len(df))
    df.to_parquet(dest, index=False)

    # Register the file with DVC so its .dvc pointer file is generated.
    logger.info("Running: dvc add %s", dest)
    subprocess.run(
        ["dvc", "add", str(dest)],
        check=True,
        capture_output=True,
        text=True,
    )
    logger.info("DVC snapshot registered for %s", dest)

    # Compute SHA-256 of the raw Parquet bytes for the audit log.
    sha256 = _sha256_file(dest)
    logger.info(
        "Snapshot complete — name=%r path=%s sha256=%s", name, dest, sha256
    )
    return sha256


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------


def _sha256_file(path: Path) -> str:
    """Return the hex SHA-256 digest of *path* using a streaming 64-KiB read.

    Args:
        path: Path to the file to hash.

    Returns:
        64-character lowercase hex string.
    """
    h = hashlib.sha256()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(65_536), b""):
            h.update(chunk)
    return h.hexdigest()
